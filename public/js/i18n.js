export const LANGUAGES = Object.keys(DICTIONARY);

let current = 'en';

// `choice` is a settings value: 'auto' follows the browser.
export function setLanguage(choice) {
  const wanted = choice === 'auto' ? (globalThis.navigator?.language ?? 'en').slice(0, 2) : choice;
  current = LANGUAGES.includes(wanted) ? wanted : 'en';
  if (globalThis.document) document.documentElement.lang = current;
}

export const has = (key) => key in DICTIONARY[current];

export function t(key, params = {}) {
  const text = DICTIONARY[current][key] ?? DICTIONARY.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}

// Picks `${key}.one` or `${key}.other` and fills in {n}.
export const tn = (key, n, params = {}) => t(`${key}.${n === 1 ? 'one' : 'other'}`, { ...params, n });

export const dictionaries = DICTIONARY;
